export const PRODUCTS: Product[] = seeds.map((s, i) => {
  const { rating, reviews, ...rest } = s;
  const id = `p${(i + 1).toString().padStart(3, '0')}`;
  const reviewList = reviews ?? [];
  const avgRating = rating ?? (reviewList.length ? reviewList.reduce((a, r) => a + r.rating, 0) / reviewList.length : 4.5);
  return {
    ...rest,
    id,
    sku: sku('VRN'),
    rating: Math.round(avgRating * 10) / 10,
    reviews: reviewList,
    reviewCount: reviewList.length + Math.floor(Math.random() * 40) + 5,
    specs: (rest.specs as any).map((sp: [string, string]) => ({ label: sp[0], value: sp[1] })),
  } as Product;
});

export function getProductById(id: string): Product | undefined {
  return PRODUCTS.find((p) => p.id === id);
}

export function productsByGender(gender: 'men' | 'women' | 'kids'): Product[] {
  return PRODUCTS.filter((p) => p.gender === gender);
}

export function productsByCategory(category: string): Product[] {
  return PRODUCTS.filter((p) => p.category === category);
}
