import type { Product, Review } from '@/types';

let skuSeq = 1000;
function sku(prefix: string): string {
  skuSeq += 7;
  return `${prefix}-${skuSeq}`;
}

function rev(id: number, name: string, rating: number, daysAgo: number, title: string, body: string): Review {
  const d = new Date();
  d.setDate(d.getDate() - daysAgo);
  return {
    id: `r${id}`,
    name,
    rating,
    date: d.toISOString(),
    title,
    body,
  };
}

